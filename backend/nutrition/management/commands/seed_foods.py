class Command(BaseCommand):
    help = 'Seed the database with standard generic foods and cooked dishes (like FatSecret).'

    def handle(self, *args, **options):
        created_count = 0
        for item in COMMON_FOODS:
            _, created = Food.objects.update_or_create(
                name=item['name'],
                owner=None,  # Global shared food
                defaults={
                    'brand': item['brand'],
                    'calories_per_100g': Decimal(item['calories']),
                    'protein_per_100g': Decimal(item['protein']),
                    'fat_per_100g': Decimal(item['fat']),
                    'carbs_per_100g': Decimal(item['carbs']),
                    'source': Food.Source.MANUAL,
                },
            )
            if created:
                created_count += 1

        self.stdout.write(
            self.style.SUCCESS(
                f'Done! Successfully seeded {created_count} common cooked foods '
                f'({len(COMMON_FOODS) - created_count} already existed).'
            )
        )
